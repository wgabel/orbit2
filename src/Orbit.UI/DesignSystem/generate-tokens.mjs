// Build-time design token compiler. Uses only Node's standard library and
// produces a deterministic stylesheet, with no additional browser runtime.
import { readFile, writeFile } from "node:fs/promises";
import { resolve } from "node:path";
import { fileURLToPath, pathToFileURL } from "node:url";

const directory = new URL("./", import.meta.url);
const output = new URL("../wwwroot/css/tokens.css", directory);
const segment = /^[a-z0-9]+(?:-[a-z0-9]+)*$/;
const reference = /^\{([a-z0-9-]+(?:\.[a-z0-9-]+)+)\}$/;

function flatten(object, prefix = "", entries = new Map()) {
    if (!object || typeof object !== "object" || Array.isArray(object) || !Object.keys(object).length)
        throw new Error("Expected non-empty token group: " + (prefix || "root"));

    for (const [key, value] of Object.entries(object)) {
        if (!segment.test(key))
            throw new Error("Invalid token name: " + key);
        const path = prefix ? prefix + "." + key : key;
        if (typeof value === "string") {
            // References are the only supported way to compose tokens. Raw CSS
            // declarations or variable expressions must not bypass validation.
            if (!reference.test(value) && (!value.trim() || /[;{}<>\r\n]|var\s*\(/i.test(value)))
                throw new Error("Invalid CSS token value: " + path);
            entries.set(path, value);
        } else {
            flatten(value, path, entries);
        }
    }
    return entries;
}

function cssName(path) {
    return "--" + path.replaceAll(".", "-");
}

function validate(entries) {
    const names = new Set();
    const complete = new Set();
    const visiting = new Set();

    function visit(path) {
        if (complete.has(path)) return;
        if (visiting.has(path)) throw new Error("Circular token reference: " + path);
        if (!entries.has(path)) throw new Error("Unknown token reference: " + path);
        visiting.add(path);
        const target = reference.exec(entries.get(path))?.[1];
        if (target) visit(target);
        visiting.delete(path);
        complete.add(path);
    }

    for (const path of entries.keys()) {
        const name = cssName(path);
        if (names.has(name)) throw new Error("Duplicate CSS variable: " + name);
        names.add(name);
        visit(path);
    }
}

function themeEntries(theme, base) {
    const entries = flatten(theme);
    for (const path of entries.keys()) {
        if (!path.startsWith("semantic.color."))
            throw new Error("Theme may only define semantic colors: " + path);
        if (base.has(path))
            throw new Error("Theme color must not duplicate a shared token: " + path);
    }
    return entries;
}

function declaration([path, value]) {
    const target = reference.exec(value)?.[1];
    return "    " + cssName(path) + ": " + (target ? "var(" + cssName(target) + ")" : value) + ";";
}

/** Build the default and alternate theme scopes; reject invalid token graphs. */
export function generateTokensCss(shared, darkTheme, lightTheme) {
    const base = flatten(shared);
    const groups = new Set(Object.keys(shared));
    if (groups.size !== 3 || !["primitive", "semantic", "component"].every(key => groups.has(key)))
        throw new Error("Expected primitive, semantic and component token groups");

    const dark = themeEntries(darkTheme, base);
    const light = themeEntries(lightTheme, base);
    if (dark.size !== light.size || [...dark.keys()].some(key => !light.has(key)))
        throw new Error("Dark and light themes must define identical semantic color keys");

    const defaultTokens = new Map([...base, ...dark]);
    validate(defaultTokens);
    validate(new Map([...base, ...light]));

    return [
        "/* Generated by DesignSystem/generate-tokens.mjs. Do not edit.",
        "   Change design-tokens.json or Themes/*.json, then regenerate. */",
        ":root {",
        ...[...defaultTokens].map(declaration),
        "}",
        "",
        '/* Explicit root theme; dark is the default. */',
        ':root[data-theme="light"] {',
        ...[...light].map(declaration),
        "}",
        ""
    ].join("\n");
}

export async function readTokenFiles() {
    const readJson = async path => JSON.parse(await readFile(new URL(path, directory), "utf8"));
    return Promise.all([
        readJson("design-tokens.json"),
        readJson("Themes/dark.json"),
        readJson("Themes/light.json")
    ]);
}

async function main(args) {
    if (args.length > 1 || (args.length && args[0] !== "--check"))
        throw new Error("Usage: node generate-tokens.mjs [--check]");
    const css = generateTokensCss(...await readTokenFiles());
    if (args[0] === "--check") {
        if ((await readFile(output, "utf8")).replaceAll("\r\n", "\n") !== css)
            throw new Error("Generated tokens.css is stale. Run the token generator.");
        console.log("Design tokens are up to date.");
    } else {
        await writeFile(output, css, "utf8");
        console.log("Generated " + fileURLToPath(output));
    }
}

if (process.argv[1] && pathToFileURL(resolve(process.argv[1])).href === import.meta.url) {
    main(process.argv.slice(2)).catch(error => {
        console.error(error.message);
        process.exitCode = 1;
    });
}
